import assert from 'node:assert/strict';
import {comparison,compareMarkup} from '../src/product-compare.mjs';
import {render} from '../src/render.mjs';
import {catalogPage} from '../src/live-catalog.mjs';
import {pageBucket} from '../src/metrics.mjs';
const product=(id,name,price,rocket=false)=>({productId:String(id),productName:name,productPrice:price,productImage:'https://ads-partners.tw.coupang.com/image.png',productUrl:'https://coupa.ng/test'+id,categoryName:'Test',isRocket:rocket});
const a=product(1,'A <script>',50,true),b=product(2,'B',75),c=product(3,'C',100),d=product(4,'D',125);
const snapshot={version:1,fetchedAt:new Date().toISOString(),deals:[a,b],categories:[{categoryId:1,categoryName:'Test',available:true,products:[a,c,d]}],guides:{}};
const query=new URLSearchParams('id=1&id=1&id=2&id=99&id=4');
const {selected,missing,pool}=comparison(snapshot,query);
assert.deepEqual(selected.map(p=>p.productId),['1','2']);
assert.equal(missing,1);assert.equal(pool.length,4);
const pages=render([],[],'',snapshot,query);
const html=pages['compare/index.html'];
assert(html.includes('A &lt;script&gt;'));
assert(!html.includes('A <script>'));
assert(html.includes('所選商品中價格最低'));
assert(html.includes('部分商品已不在最新快照'));
assert(html.includes('rel="sponsored nofollow noopener noreferrer"'));
assert(html.includes('content="noindex,follow"'));
assert(!render([],[],'https://hicrewapps.com')['sitemap.xml'].includes('/compare/'));
assert(render([],[])['compare/index.html'].includes('商品資料暫未同步'));
assert.equal(pageBucket('/compare/index.html',[]),'/compare/');
assert.equal(comparison(snapshot,new URLSearchParams('id=1&id=2&id=3&id=4')).selected.length,3);
assert.equal(comparison(null,query).selected.length,0);
